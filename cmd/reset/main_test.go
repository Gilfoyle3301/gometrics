package main

import (
	"os"
	"os/exec"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func copyFixture(t *testing.T, dir string) {
	t.Helper()

	for _, name := range []string{"go.mod", "types.go", "reset_behavior_test.go"} {
		data, err := os.ReadFile(filepath.Join("testdata", "resetfixture", name))
		require.NoError(t, err)
		require.NoError(t, os.WriteFile(filepath.Join(dir, name), data, 0o644))
	}
}

func TestGenerateTree(t *testing.T) {
	dir := t.TempDir()
	copyFixture(t, dir)

	count, err := generateTree(dir)
	require.NoError(t, err)
	require.Equal(t, 1, count)

	src, err := os.ReadFile(filepath.Join(dir, genFileName))
	require.NoError(t, err)

	content := string(src)
	assert.Contains(t, content, "// Code generated by cmd/reset. DO NOT EDIT.")
	assert.Contains(t, content, "package resetfixture")
	assert.Contains(t, content, `"time"`)
	assert.Contains(t, content, "func (s *Sample) Reset()")
	assert.Contains(t, content, "if s == nil {")
	assert.Contains(t, content, "s.i = 0")
	assert.Contains(t, content, `s.str = ""`)
	assert.Contains(t, content, "s.b = false")
	assert.Contains(t, content, "s.s = s.s[:0]")
	assert.Contains(t, content, "clear(s.m)")
	assert.Contains(t, content, "s.child.Reset()")
	assert.Contains(t, content, "s.kid.Reset()")
	assert.Contains(t, content, `*s.strP = ""`)
	assert.Contains(t, content, "s.dur = *new(time.Duration)")
	assert.Contains(t, content, "s.iface = nil")
	assert.Contains(t, content, "s.ch = nil")
	assert.Contains(t, content, "func (n *Node) Reset()")
	assert.Contains(t, content, "n.Next.Reset()")
	assert.NotContains(t, content, "s._")

	cmd := exec.Command("go", "test", "./...")
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	require.NoError(t, err, "generated code must compile and behave correctly:\n%s", out)
}

func TestGenerateTreeIdempotent(t *testing.T) {
	dir := t.TempDir()
	copyFixture(t, dir)

	_, err := generateTree(dir)
	require.NoError(t, err)

	first, err := os.ReadFile(filepath.Join(dir, genFileName))
	require.NoError(t, err)

	count, err := generateTree(dir)
	require.NoError(t, err)
	require.Equal(t, 1, count)

	second, err := os.ReadFile(filepath.Join(dir, genFileName))
	require.NoError(t, err)

	assert.Equal(t, first, second)
}

func TestGenerateTreeNoMarkedStructs(t *testing.T) {
	dir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module nomark\n\ngo 1.22\n"), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(dir, "plain.go"), []byte("package nomark\n\ntype Plain struct{ I int }\n"), 0o644))

	count, err := generateTree(dir)
	require.NoError(t, err)
	assert.Equal(t, 0, count)

	_, statErr := os.Stat(filepath.Join(dir, genFileName))
	assert.True(t, os.IsNotExist(statErr))
}

