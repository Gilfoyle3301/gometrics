// Command staticlint — multichecker для статического анализа исходного кода
// gometrics. Объединяет стандартные анализаторы golang.org/x/tools, все
// проверки staticcheck классов SA, S, ST и QF, два сторонних публичных
// анализатора и собственный анализатор osexit.
//
// # Механизм запуска
//
// Multichecker собран на golang.org/x/tools/go/analysis/multichecker и
// принимает шаблоны пакетов так же, как go build:
//
//	go run ./cmd/staticlint ./...
//
// либо собранным бинарным файлом:
//
//	go build -o staticlint ./cmd/staticlint
//	./staticlint ./...
//
// Возможен запуск и через go vet:
//
//	go vet -vettool=./staticlint ./...
//
// Ненулевой код возврата означает, что анализаторы нашли замечания.
// Флаг -h печатает список всех зарегистрированных анализаторов; каждый
// можно отключить individually флагом -<имя>=false, например -printf=false.
//
// # Стандартные анализаторы golang.org/x/tools/go/analysis/passes
//
//   - appends — ошибки семантики append (перезапись среза, append в сам себя);
//   - assign — бессмысленные присваивания переменной самой себе;
//   - atomic — типовые ошибки использования sync/atomic;
//   - bools — дублирующиеся условия и упрощаемые булевы выражения;
//   - buildtag — корректность синтаксиса и расположения //go:build-директив;
//   - composite — неключевые составные литералы структур из других пакетов;
//   - copylock — копирование значений, содержащих мьютексы и другие блокировки;
//   - defers — ошибки в отложенных вызовах (defer внутри цикла, неверные аргументы);
//   - directive — синтаксис и расположение директив //go:;
//   - errorsas — корректность второго аргумента errors.As (указатель на ошибку);
//   - httpresponse — использование http.Response после непроверенной ошибки;
//   - ifaceassert — заведомо ложные утверждения типа «интерфейс-инфейс»;
//   - loopclosure — захват переменной цикла в замыкании;
//   - lostcancel — потерянный context.CancelFunc (отмена не будет вызвана);
//   - nilfunc — сравнение функций с nil (всегда false);
//   - nilness — разыменование nil и заведомо недостижимые nil-проверки;
//   - printf — соответствие форматных строк и аргументов в print-подобных вызовах;
//   - slog — ошибки использования log/slog (нечётные пары аргументов, nil-значения);
//   - sortslice — сортировка неподходящих типов (sort.Slice с не-срезом или неверной less-функцией);
//   - sqlrowserr — непроверенный rows.Err у database/sql;
//   - stdmethods — соответствие сигнатур канонических методов (MarshalJSON, WriteTo и др.);
//   - stringintconv — подозрительные преобразования string(int) (печатают символ, а не число);
//   - structtag — синтаксис и дубликаты в struct-тегах;
//   - tests — ошибки в тестах: сигнатуры Test*/Benchmark*/Example*, неверные имена;
//   - timeformat — неверные константы в time.Format (например "2020-01-02" вместо "2006-01-02");
//   - unmarshal — некорректный приёмник для json/xml Unmarshal (не указатель);
//   - unreachable — недостижимый код после return/panic/break;
//   - unusedresult — проигнорированные результаты вызовов, которые обязаны использоваться;
//   - unusedwrite — запись в поле структуры, которое нигде не читается;
//   - waitgroup — ошибки использования sync.WaitGroup (Add после Wait и т.п.).
//
// # Staticcheck (модуль honnef.co/go/tools, v0.8.2)
//
// Модуль staticcheck.io недоступен для go get (vanity-домен не отдаёт
// go-get-метаданные), поэтому используется его опубликованная на proxy
// копия под историческим путём honnef.co/go/tools той же версии.
// Подключены все анализаторы всех классов; каждый несёт собственную
// godoc-документацию и ссылку на https://staticcheck.dev/docs/checks:
//
//   - SA (staticcheck) — углублённые проверки корректности: ошибки API,
//     неверные аргументы, гонки, некорректные тесты (SA1000–SA9004);
//   - S (simple, gosimple) — упрощение кода без изменения поведения
//     (S1000–S1040);
//   - ST (stylecheck) — стиль: именование, формат комментариев, ошибки
//     в тексте ошибок (ST1000–ST1023);
//   - QF (quickfix) — рекомендуемые быстрые правки: tagged switch,
//     strings.Builder, fmt.Fprintf и т.п. (QF1001–QF1012).
//
// # Сторонние публичные анализаторы
//
//   - ineffassign (github.com/gordonklaus/ineffassign/pkg/ineffassign) — присваивания,
//     значение которых никогда не используется до следующего присваивания
//     или конца области видимости;
//   - bodyclose (github.com/timakin/bodyclose/passes/bodyclose) — незакрытые
//     тела HTTP-ответов (resp.Body.Close обязателен даже при ошибке).
//
// # Собственный анализатор osexit
//
// Запрещает прямой вызов os.Exit в функции main пакета main: os.Exit
// пропускает все defer, из-за чего сервер теряет финальный сброс метрик
// и корректное закрытие ресурсов. Анализатор срабатывает только на
// лексически прямые вызовы os.Exit внутри func main; вызовы в остальных
// функциях (например, в вынесенной run) разрешены. Обход через присвоенную
// переменную или log.Fatal анализатор сознательно не отслеживает — задание
// требует запрещать именно прямой вызов. Сгенерированные файлы, включая
// служебный main тестового бинарника («Code generated by 'go test'»),
// анализатором пропускаются.
